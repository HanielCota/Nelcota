CREATE FUNCTION public.add(a integer, b integer DEFAULT 10) RETURNS integer
    LANGUAGE sql IMMUTABLE AS $$ SELECT a + b $$;
CREATE FUNCTION public.whoami() RETURNS text
    LANGUAGE sql STABLE AS $$ SELECT coalesce(auth.uid()::text, 'anon') $$;
CREATE FUNCTION public.nothing() RETURNS void LANGUAGE sql AS $$ SELECT $$;
GRANT EXECUTE ON FUNCTION public.add(integer, integer), public.whoami(), public.nothing() TO anon, authenticated;

