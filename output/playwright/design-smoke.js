async (page) => {
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  const passed = [];
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  if (await page.getByRole('dialog').count()) await page.getByRole('dialog').getByRole('button', {name: 'Cancelar', exact: true}).click();
  const go = async path => {
    await page.goto('http://127.0.0.1:5175/admin/' + path);
    await page.getByRole('heading', {level: 1}).waitFor();
    await page.waitForFunction(() => !document.querySelector('main [data-slot="skeleton"]'));
  };
  await page.setViewportSize({width: 1440, height: 900});
  await go('');
  const chart = page.getByRole('slider');
  await chart.press('Home');
  assert(await chart.getAttribute('aria-valuenow') === '0', 'Chart keyboard start');
  await chart.press('End');
  assert(Number(await chart.getAttribute('aria-valuenow')) > 0, 'Chart keyboard end');
  await page.getByRole('group', {name: 'Séries', exact: true}).getByRole('button', {name: 'Requisições', exact: true}).click();
  assert(await page.getByRole('button', {name: 'Requisições', exact: true}).getAttribute('aria-pressed') === 'true', 'Series selection');
  await page.getByRole('button', {name: 'Ver como tabela', exact: true}).click();
  await page.getByRole('columnheader', {name: 'Horário', exact: true}).waitFor();
  await page.getByRole('button', {name: 'Esconder tabela', exact: true}).click();
  await page.getByRole('button', {name: '1 hora', exact: true}).click();
  assert(await page.getByRole('button', {name: '1 hora', exact: true}).getAttribute('aria-pressed') === 'true', 'Period selection');
  passed.push('Chart keyboard, series, period and table view');
  await page.getByRole('main').getByRole('link', {name: 'Novo usuário', exact: true}).click();
  const user = page.getByRole('dialog', {name: 'Novo usuário', exact: true});
  await user.waitFor();
  await page.screenshot({path: 'output/playwright/design-dialog-user.png', scale: 'css'});
  await page.setViewportSize({width: 390, height: 844});
  assert(await user.evaluate(el => { const box = el.getBoundingClientRect(); return box.left >= 0 && box.right <= innerWidth; }), 'User dialog fits mobile');
  await page.screenshot({path: 'output/playwright/design-dialog-user-mobile.png', scale: 'css'});
  await user.getByRole('button', {name: 'Cancelar', exact: true}).click();
  passed.push('Quick action and responsive user dialog');
  await page.setViewportSize({width: 1440, height: 900});
  await go('tables');
  const search = page.getByRole('searchbox', {name: 'Buscar tabelas…'});
  await search.fill('inexistente');
  await page.getByRole('complementary').getByText('Nenhum resultado para esses filtros', {exact: true}).waitFor();
  await page.getByRole('complementary').getByRole('button', {name: 'Limpar busca', exact: true}).first().click();
  assert(await search.inputValue() === '', 'Search clears');
  assert(await search.evaluate(el => document.activeElement === el), 'Search retains focus');
  await page.getByRole('complementary').getByRole('link', {name: 'notes', exact: true}).click();
  await page.getByRole('link', {name: 'Estrutura', exact: true}).click();
  await page.waitForURL('**/tables/notes/structure');
  passed.push('Search recovery and table navigation');
  await go('policies?table=profiles');
  const policySearch = page.getByRole('searchbox', {name: 'Buscar tabela'});
  assert(await policySearch.inputValue() === 'profiles', 'Linked table filter');
  await policySearch.fill('notes');
  await page.getByRole('button', {name: 'Sem proteção', exact: true}).click();
  await page.waitForURL(/filter=disabled/);
  await page.getByRole('button', {name: 'Limpar filtros', exact: true}).click();
  await page.getByRole('heading', {name: 'notes', exact: true}).waitFor();
  passed.push('Policy filters and clear');
  await go('storage');
  await page.getByRole('searchbox', {name: 'Buscar buckets'}).fill('inexistente');
  await page.getByRole('main').getByText('Nenhum resultado para esses filtros', {exact: true}).waitFor();
  await page.getByRole('main').getByRole('button', {name: 'Limpar busca', exact: true}).first().click();
  await page.getByRole('button', {name: 'Novo bucket', exact: true}).click();
  const bucket = page.getByRole('dialog', {name: 'Novo bucket', exact: true});
  await bucket.waitFor();
  await page.screenshot({path: 'output/playwright/design-dialog-bucket.png', scale: 'css'});
  await bucket.getByRole('button', {name: 'Cancelar', exact: true}).click();
  passed.push('Storage search and bucket dialog');
  await page.setViewportSize({width: 390, height: 844});
  await page.getByRole('button', {name: 'Menu', exact: true}).click();
  await page.getByRole('dialog').getByRole('link', {name: 'API', exact: true}).click();
  await page.getByRole('heading', {name: 'API', exact: true}).waitFor();
  await page.getByRole('dialog').waitFor({state: 'hidden'});
  await page.getByRole('link', {name: 'Conectar meu app', exact: true}).click();
  await page.waitForFunction(() => {
    const top = document.getElementById('api-sdk').getBoundingClientRect().top;
    const mainTop = document.querySelector('main').getBoundingClientRect().top;
    return top >= mainTop - 1 && top < mainTop + 130;
  });
  await page.getByRole('button', {name: 'JavaScript', exact: true}).click();
  await page.waitForURL(/lang=js/);
  assert(await page.getByRole('main').evaluate(el => el.scrollWidth <= el.clientWidth), 'Mobile API content fits');
  passed.push('Mobile navigation, SDK anchor and language');
  await go('projects');
  await page.getByText('Novo projeto', {exact: true}).click();
  assert(await page.locator('details[open]').count() === 1, 'Project instructions disclosure opens');
  passed.push('Project instructions disclosure');
  return {passed, pageErrors: errors};
}
